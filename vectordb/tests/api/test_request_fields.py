#: Request bodies with no schema to enumerate. `POST /query` takes a DXQL statement as free JSON
#: and has no typed body at all, so there are no properties for this suite to be complete about;
#: `tests/api/test_query.py` covers it by statement instead.
UNTYPED_BODIES = {"/api/v1/query"}


@pytest.fixture(scope="module")
def spec():
    """The served OpenAPI document. Fetched with urllib because it sits outside `/api/v1`."""
    root = BASE[: -len("/api/v1")]
    try:
        with urllib.request.urlopen(f"{root}/api/docs/openapi.json", timeout=10) as response:
            return json.load(response)
    except (urllib.error.URLError, OSError, json.JSONDecodeError) as exc:
        message = (f"no OpenAPI document at {root}/api/docs/openapi.json ({exc}): build with "
                   f"--features api-swagger and start the server with --swagger")
        if declared("api-swagger"):
            pytest.fail(f"DXMT_FEATURES says the server has api-swagger, but there is {message}")
        pytest.skip(message)


def documented_fields(spec):
    """Every (schema, property) a request body in the document exposes."""
    schemas = spec.get("components", {}).get("schemas", {})
    out = set()
    for path, operations in spec["paths"].items():
        if path in UNTYPED_BODIES:
            continue
        for operation in operations.values():
            body = (operation or {}).get("requestBody")
            if not body:
                continue
            reference = (body.get("content", {}).get("application/json", {})
                         .get("schema", {}).get("$ref", ""))
            name = reference.rsplit("/", 1)[-1]
            if not name:
                continue
            properties = schemas.get(name, {}).get("properties")
            assert properties is not None, (
                f"{path} takes a {name} body, and {name} is not in components/schemas — utoipa "
                f"emitted a $ref to a schema it never defined, so the documentation shows this "
                f"operation with no fields at all. Add it to `components(schemas(...))` in "
                f"src/api/swagger.rs."
            )
            for field in properties:
                out.add((name, field))
    return out


def test_every_documented_field_has_a_probe(spec):
    """A field a caller can send must have a test that fails when nothing reads it.

    This is the part that keeps the suite honest as the API grows. The field list comes from the
    served document, which utoipa generates from the request structs themselves, so a field
    added to a struct shows up here without anyone remembering to add it — and this test goes
    red until a probe exists. A hand-written list would drift; this cannot.
    """
    documented = documented_fields(spec)
    missing = sorted(documented - set(PROBES))
    assert not missing, (
        "these request fields are documented and have no probe, so nothing would notice if the "
        "server stopped reading them:\n  "
        + "\n  ".join(f"{schema}.{field}" for schema, field in missing)
        + "\n\nAdd a @probe to tests/api/test_request_fields.py for each. A probe has to send a "
          "request the field changes the answer to — asserting a 200 proves nothing, which is "
          "the state every field this suite was written for was already in."
    )

    # And the other direction: a probe for a field that no longer exists is dead weight that
    # reads like coverage.
    stale = sorted(set(PROBES) - documented)
    assert not stale, (
        "these probes name fields the document no longer has:\n  "
        + "\n  ".join(f"{schema}.{field}" for schema, field in stale)
    )


def pytest_generate_tests(metafunc):
    """Parametrise from `PROBES` at collection time rather than at decoration time.

    The obvious spelling -- `@pytest.mark.parametrize("key", sorted(PROBES))` -- reads the table
    at the moment the decorator runs, part way down this file. A probe registered *below* the
    test function is then registered, counted as covered by the completeness check, and never
    actually run. Two were, and the suite reported 58 passing while running 56 of them: the
    exact failure this file exists to catch, in this file. This hook is called after the module
    is fully imported, so where a probe sits cannot matter.
    """
    if "key" in metafunc.fixturenames:
        metafunc.parametrize("key", sorted(PROBES), ids=lambda k: f"{k[0]}.{k[1]}")


def test_the_field_changes_the_answer(key, table, request):
    """Run one probe. Each sends a request the field must change, and checks that it did."""
    probe_fn = PROBES[key]
    if "alterable" in probe_fn.__code__.co_varnames[: probe_fn.__code__.co_argcount]:
        probe_fn(table, request.getfixturevalue("alterable"))
    else:
        probe_fn(table)


