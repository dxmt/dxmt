"""Every documented request field does something, and every one is covered here.

This suite exists because of what an audit of the HTTP surface turned up: fields that a caller
can send, that the server answers 200 to, and that nothing reads. They are invisible in every
other way. `named_vectors` on `POST /tables` was dropped on the floor, so a table created with
named vector spaces came back reporting none, and a later search naming one of them silently
scored against the default vector instead -- a *wrong answer*, not an error. `fuzzy` on
`/search/text` is threaded from the request through to the engine's own config struct and then
never read. Nothing in a log, nothing in a response.

Two properties are checked, and the first is the one that makes this durable:

**Completeness.** `test_every_documented_field_has_a_probe` reads the served OpenAPI document,
enumerates every property of every request body in it, and fails if any of them is missing from
`PROBES`. The document is generated by utoipa from the actual request structs, so a field added
to a struct appears here by itself and turns this red until someone writes a probe for it. A
hand-maintained list would have drifted the way everything else here has drifted.

**Behaviour.** Each probe sends a request that the field must change the answer to, and checks
that it did. "Sent it and got a 200" proves nothing at all -- that is exactly the state every
one of these bugs was in.

A probe that cannot fail is worse than no probe, so each one is written to be a discriminator:
`fields=["title"]` against a corpus where only one document has the term in its title, `offset`
against a page that must not repeat, `vector_weight` against two settings that must score
differently. Where a field's honest behaviour is "accepted and inert", that is stated in the
probe rather than hidden behind an assertion that happens to pass.

Run with a text-bm25 build to cover the full-text and hybrid fields; without it those probes
skip, and `DXMT_FEATURES` turns the skip into a failure as elsewhere in this suite.
"""

import json
import os
