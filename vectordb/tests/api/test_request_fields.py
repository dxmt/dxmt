# --------------------------------------------------------------------------------------------
# The corpus every probe shares.
#
# Five records, built so that several different things are each true of exactly one subset:
# the dense ranking is r0..r4, only r0 has "widgets" in its *title*, topic splits 3/2, each
# record owns one sparse dimension, and `n` counts up. That is what lets a probe be a
# discriminator rather than a smoke test.
# --------------------------------------------------------------------------------------------

VECTORS = [[1, 0, 0, 0], [0.9, 0.4, 0, 0], [0.7, 0.7, 0, 0], [0.4, 0.9, 0, 0], [0, 1, 0, 0]]
QUERY = [1.0, 0.0, 0.0, 0.0]


def records():
    out = []
    for i, vector in enumerate(VECTORS):
        out.append(
            {
                "id": f"r{i}",
                "vector": vector,
                "sparse_vector": {"indices": [i], "values": [1.0], "dimension": 16},
                "payload": {
                    "topic": "alpha" if i < 3 else "beta",
                    "n": i,
                    "title": "widgets in the title" if i == 0 else f"title {i}",
                    "content": f"document number {i} about widgets",
                },
            }
        )
    return out


def declared(feature):
    return feature in {f for f in re.split(r"[,\s]+", os.environ.get("DXMT_FEATURES", "")) if f}


def needs_text(response):
    """Skip -- or fail, when the run said the feature is present -- on an absent text index."""
    body = response.json() or {}
    code = ((body.get("error") or {}).get("code")) or ""
    if code in {"FEATURE_DISABLED", "FULL_TEXT_NOT_ENABLED"}:
        if declared("text-bm25"):
            pytest.fail(f"DXMT_FEATURES says text-bm25 is present, but the server said {code}")
        pytest.skip(f"server answered {code}")
    return response


@pytest.fixture(scope="module")
def table():
    name = f"rf_{uuid.uuid4().hex[:8]}"
    post(
        "/tables",
        {
            "name": name,
            "dimension": 4,
            "distance_metric": "cosine",
            "description": "request-field probes",
            "enable_full_text_search": True,
            "text_fields": [
                {"name": "content", "source": {"metadata_field": "content"}, "weight": 1.0},
                {"name": "title", "source": {"metadata_field": "title"}, "weight": 2.0},
            ],
        },
    )
    post(f"/tables/{name}/records", {"records": records()})
    yield name
    delete(f"/tables/{name}", expect_ok=False)


# --------------------------------------------------------------------------------------------
# Probes. One per documented field; the key is (schema name, property name) exactly as the
# OpenAPI document spells them.
# --------------------------------------------------------------------------------------------

def search(table, **body):
    return post(f"/tables/{table}/search", {"vector": QUERY, "top_k": 5, "limit": 5, **body})


def ids(response):
    return [hit["id"] for hit in response.json()["data"]["hits"]]


def listed(table, **body):
    return post(f"/tables/{table}/records/list", {"limit": 5, **body}).json()["data"]


def text(table, **body):
    return post(f"/tables/{table}/search/text", {"query": "widgets", "limit": 9, **body},
                expect_ok=False)


def hybrid(table, **body):
    return post(f"/tables/{table}/search/hybrid",
                {"vector": QUERY, "text": "widgets", "limit": 5, **body}, expect_ok=False)


PROBES = {}


def probe(schema, field):
    def register(fn):
        PROBES[(schema, field)] = fn
        return fn
    return register


