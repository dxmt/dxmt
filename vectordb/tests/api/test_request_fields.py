@probe("HybridSearchRequest", "fusion_method")
def _(table):
    rrf = needs_text(hybrid(table, fusion_method="reciprocal_rank_fusion")).json()["data"]["hits"]
    dbsf = needs_text(hybrid(table, fusion_method="dbsf")).json()["data"]["hits"]
    assert [round(h["score"], 6) for h in rrf] != [round(h["score"], 6) for h in dbsf]


@probe("HybridSearchRequest", "vector_weight")
def _(table):
    # Read by `weighted_sum` and, despite the name, by `reciprocal_rank_fusion` too: that one is
    # a *weighted* RRF, scaling each side's 1/(k+rank). Only `dbsf` ignores it.
    #
    # The text has to be one the two halves disagree about. With a query every document matches
    # equally the two rankings coincide, every score becomes w/(k+r) + (1-w)/(k+r) = 1/(k+r),
    # and the weight cancels out exactly -- a probe written that way passes whatever the server
    # does with the field. "number 4" puts r4 first on the text side and it is last on the dense
    # side, so the weight decides which of them wins.
    heavy = ids(needs_text(hybrid(table, text="number 4",
                                  fusion_method="reciprocal_rank_fusion", vector_weight=0.95)))
    light = ids(needs_text(hybrid(table, text="number 4",
                                  fusion_method="reciprocal_rank_fusion", vector_weight=0.05)))
    assert heavy[0] == "r0", heavy
    assert light[0] == "r4", light


@probe("HybridSearchRequest", "rrf_k")
def _(table):
    small = needs_text(hybrid(table, fusion_method="reciprocal_rank_fusion",
                              rrf_k=1)).json()["data"]["hits"]
    large = needs_text(hybrid(table, fusion_method="reciprocal_rank_fusion",
                              rrf_k=600)).json()["data"]["hits"]
    assert [round(h["score"], 6) for h in small] != [round(h["score"], 6) for h in large]


@probe("HybridSearchRequest", "sparse_vector")
def _(table):
    # r4 is last on the dense ranking and owns sparse dimension 4, so the postings are the only
    # thing that can lift it.
    without = ids(needs_text(hybrid(table, fusion_method="dbsf")))
    with_sparse = ids(needs_text(hybrid(
        table, fusion_method="dbsf",
        sparse_vector={"indices": [4], "values": [1.0], "dimension": 16})))
    assert with_sparse != without, f"the sparse half changed nothing: {with_sparse}"


