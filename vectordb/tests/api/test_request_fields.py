@probe("SearchQuery", "vector_name")
def _(table):
    # Named vector spaces are declared at table creation, and the space here is deliberately
    # the opposite way round from the default vector: r4 is last on the default ranking and
    # first on `title`. A `vector_name` that is silently ignored returns the default order.
    name = f"{table}_named"
    post("/tables", {"name": name, "dimension": 4, "distance_metric": "cosine",
                     "named_vectors": [{"name": "title", "dimension": 4,
                                        "distance_metric": "cosine"}]})
    try:
        declared_spaces = get(f"/tables/{name}").json()["data"]["table"]["named_vectors"]
        assert declared_spaces, (
            "the table reports no named vector spaces, so `named_vectors` was dropped on the "
            "way in and no named index exists for `vector_name` to reach"
        )
        post(f"/tables/{name}/records", {"records": [
            {"id": f"n{i}", "vector": v, "named_vectors": {"title": VECTORS[4 - i]}}
            for i, v in enumerate(VECTORS)]})
        default = ids(post(f"/tables/{name}/search",
                           {"vector": QUERY, "top_k": 5, "limit": 5}))
        named = ids(post(f"/tables/{name}/search",
                         {"vector": QUERY, "top_k": 5, "limit": 5, "vector_name": "title"}))
        assert named != default, f"vector_name changed nothing: {named}"
        assert named[0] == "n4", named
    finally:
        delete(f"/tables/{name}", expect_ok=False)


@probe("SearchQuery", "mmr")
def _(table):
    # The shared corpus is a line of five vectors sweeping from r0 to r4, so the plain top-2 is
    # r0, r1 -- adjacent and nearly the same. At full diversity the second pick is the far end.
    plain = ids(search(table, limit=2))
    assert plain == ["r0", "r1"], plain
    diverse = ids(search(table, limit=2, mmr={"lambda_mult": 0.0, "fetch_k": 5}))
    assert diverse[0] == "r0", diverse
    assert diverse[1] != "r1", f"nothing was diversified: {diverse}"
    # And 1.0 is the plain ranking, which is the half that proves the parameter is read rather
    # than the endpoint simply behaving differently when `mmr` is present.
    assert ids(search(table, limit=2, mmr={"lambda_mult": 1.0, "fetch_k": 5})) == plain


@probe("SearchQuery", "offset")
def _(table):
    # The pages have to tile: page two is the tail of the unpaged answer, not a second copy of
    # page one. An `offset` that was accepted and ignored would return r0 twice.
    # `limit`, not `top_k`: the shared helper sends both, and the server prefers `limit` when
    # it is set to anything but its default -- so overriding `top_k` alone changes nothing.
    whole = [h["id"] for h in search(table, limit=4).json()["data"]["hits"]]
    second = [h["id"] for h in search(table, limit=2, offset=2).json()["data"]["hits"]]
    assert second == whole[2:4], (whole, second)


@probe("SearchQuery", "score_threshold")
def _(table):
    # A floor on the similarity, not on the internal distance -- those run in opposite
    # directions, and a threshold that meant the other one would return exactly the hits it
    # was asked to remove.
    everything = search(table, top_k=5, limit=5).json()["data"]["hits"]
    assert len(everything) > 1, everything
    floor = everything[0]["score"]
    kept = search(table, top_k=5, limit=5, score_threshold=floor).json()["data"]["hits"]
    assert kept, "the best hit is at the floor and must survive it"
    assert all(h["score"] >= floor for h in kept), kept
    assert len(kept) < len(everything), (
        f"a floor of {floor} removed nothing from {[h['score'] for h in everything]}"
    )


@probe("SearchQuery", "payload_fields")
def _(table):
    # The whole payload, then two keys of it: what is returned has to shrink, and what is kept
    # has to be the same values.
    whole = search(table, top_k=1, limit=1).json()["data"]["hits"][0]["payload"]
    assert len(whole) > 1, whole
    projected = (
        search(table, top_k=1, limit=1, payload_fields=["topic"])
        .json()["data"]["hits"][0]["payload"]
    )
    assert projected == {"topic": whole["topic"]}, projected


