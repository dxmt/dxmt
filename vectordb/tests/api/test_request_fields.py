@probe("SearchQuery", "search_mode")
def _(table):
    # `exact` scores every row, so on a corpus this small it must agree with the graph exactly.
    # An unknown mode is refused rather than ignored, which is the half that matters here.
    assert ids(search(table, search_mode="exact")) == ids(search(table, search_mode="accurate"))
    refused = post(f"/tables/{table}/search",
                   {"vector": QUERY, "top_k": 5, "search_mode": "turbo"}, expect_ok=False)
    assert refused.status_code in (400, 422), refused.status_code


@probe("SearchQuery", "vector_name")
def _(table):
    # Named vector spaces are declared at table creation, and the space here is deliberately
    # the opposite way round from the default vector: r4 is last on the default ranking and
    # first on `title`. A `vector_name` that is silently ignored returns the default order.
    name = f"{table}_named"
    post("/tables", {"name": name, "dimension": 4, "distance_metric": "cosine",
                     "named_vectors": [{"name": "title", "dimension": 4,
                                        "distance_metric": "cosine"}]})
    try:
        declared_spaces = get(f"/tables/{name}").json()["data"]["table"]["named_vectors"]
        assert declared_spaces, (
            "the table reports no named vector spaces, so `named_vectors` was dropped on the "
            "way in and no named index exists for `vector_name` to reach"
        )
        post(f"/tables/{name}/records", {"records": [
            {"id": f"n{i}", "vector": v, "named_vectors": {"title": VECTORS[4 - i]}}
            for i, v in enumerate(VECTORS)]})
        default = ids(post(f"/tables/{name}/search",
                           {"vector": QUERY, "top_k": 5, "limit": 5}))
        named = ids(post(f"/tables/{name}/search",
                         {"vector": QUERY, "top_k": 5, "limit": 5, "vector_name": "title"}))
        assert named != default, f"vector_name changed nothing: {named}"
        assert named[0] == "n4", named
    finally:
        delete(f"/tables/{name}", expect_ok=False)


