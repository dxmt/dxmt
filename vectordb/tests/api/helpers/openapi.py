"""Check every request and every response against the OpenAPI document, on every call.

The document is generated by utoipa from forty `#[utoipa::path]` annotations, so it cannot
drift from the Rust *types* -- there is no second copy to fall out of step. What it can drift
from is the *behaviour*: the annotation is written by hand next to the handler, and nothing
made the handler honour it. A response field that quietly changed name, a status the
annotation does not list, a request body the tests send and the document forbids -- all of
that was invisible, because `tests/api_contract_test.rs` checks that a route still answers,
not what it answers with.

Qdrant validates both directions on all 395 of its API test calls, through one helper every
test goes through. This is that, wired into `helpers.client.call`, so the whole suite gets it
without a line changing in any test file.

**Two rules keep this from becoming noise.**

A *request* the document rejects is a failure of the test -- unless the test passed
`expect_ok=False`, which is it saying the request is meant to be refused. A negative test
sending `top_k: -1` is supposed to violate the document, and validating it would fail the very
tests whose subject is the refusal. Everywhere else the suite is the biggest consumer of this
API, and if it sends something undocumented then either the document is wrong or the test is;
both are worth stopping for.

A *response* the document rejects is a failure only for the operations listed in `STRICT`.
Starting strict everywhere would have meant fixing forty annotations before anything ran, and
a validator that is switched off to get green is worse than none. `STRICT` is the ratchet:
`scripts/api_tests.sh` prints what is outside it, and an operation moves in when its
annotation is right. Moving one out needs a reason in the commit message.

`DXMT_OPENAPI_VALIDATE=0` turns the whole thing off, for bisecting.
"""

import os
import re

import httpx

#: Operations whose *responses* must match the document. Everything else is checked and the
#: mismatch reported at the end of the run instead of failing the test.
#:
#: Grow this list. It is in the order they were fixed, so the end of it is the current front.
STRICT = {
    ("POST", "/api/v1/tables"),
    ("GET", "/api/v1/tables"),
    ("GET", "/api/v1/tables/{table_name}"),
    ("DELETE", "/api/v1/tables/{table_name}"),
    ("GET", "/api/v1/tables/{table_name}/stats"),
    ("POST", "/api/v1/tables/{table_name}/records"),
    ("GET", "/api/v1/tables/{table_name}/records/{record_id}"),
    ("POST", "/api/v1/tables/{table_name}/search"),
    ("GET", "/api/v1/health"),
    ("GET", "/api/v1/health/metrics"),
    ("POST", "/api/v1/tables/{table_name}/branch"),
    ("POST", "/api/v1/tables/{table_name}/hybrid_search"),
    ("POST", "/api/v1/tables/{table_name}/search/groups"),
    ("POST", "/api/v1/tables/{table_name}/records/bulk"),
    ("POST", "/api/v1/tables/{table_name}/facets"),
    ("POST", "/api/v1/backup"),
}

ENABLED = os.environ.get("DXMT_OPENAPI_VALIDATE", "1") != "0"

_spec = None
_routes = None  # [(method, template, regex, operation)]
#: Response mismatches outside `STRICT`, collected and printed once. `(method, template,
#: status)` -> one example message, because a hundred copies of the same one help nobody.
observed = {}


def load(base_url):
    """Fetch the document once. Returns False when this build does not serve it."""
    global _spec, _routes
    if _spec is not None:
        return True
    if not ENABLED:
        return False
    root = base_url.rsplit("/api/v1", 1)[0]
    try:
        r = httpx.get(f"{root}/api/docs/openapi.json", timeout=30)
        if r.status_code != 200:
            return False
        _spec = r.json()
    except Exception:
        return False

    _routes = []
    for template, item in _spec["paths"].items():
        # `{table_name}` matches one segment, and a record id may be percent-encoded but is
        # still one segment. `[^/]+` is therefore right, and greedy matching across `/` is
        # what would make `/records/{id}` swallow `/records/list`.
        pattern = re.compile("^" + re.sub(r"\{[^}]+\}", "[^/]+", re.escape(template)
                                          .replace(r"\{", "{").replace(r"\}", "}")) + "$")
        for method, operation in item.items():
            if method.upper() in ("GET", "POST", "PUT", "PATCH", "DELETE"):
                _routes.append((method.upper(), template, pattern, operation))
    # A literal segment beats a parameter: `/records/list` and `/records/{id}` both match
    # `/records/list`, and only one of them is right. Sorting by the number of `{` ascending
    # puts the more literal template first, and the first match wins.
    _routes.sort(key=lambda r: r[1].count("{"))
    return True


def _resolve(node, depth=0):
    """Inline `$ref`s and turn OpenAPI 3.0 into something `jsonschema` understands.

    Two translations, both mandatory rather than cosmetic:

    **`nullable: true`.** This document is OpenAPI 3.0.3, whose Schema Object is a *dialect*
    of JSON Schema, not JSON Schema. `nullable` is its own keyword and a JSON Schema validator
    ignores it, so `{"type": "object", "nullable": true}` rejects `null` -- and the success
    envelope carries `"error": null` on every 2xx response, so without this every call in the
    suite fails for one reason. It appears 103 times here. Translated to `type: [.., "null"]`,
    and for the `allOf`/`$ref` shape utoipa emits for a nullable struct, to an `anyOf` with a
    null branch.

    **`$ref`.** Inlined, because the refs point into `components` of a document this validator
    was handed as a bare schema. Recursive schemas exist (a filter holds filters), so the depth
    cap is not optional; at the cap a subschema becomes `{}` -- "anything" -- which is the
    right way to run out of room: a validator that cannot see far enough must not invent a
    constraint it cannot check.
    """
    if not isinstance(node, (dict, list)):
        return node
    if depth > 12:
        # `{}` for *any* subtree at the cap, not just one whose own top level is a `$ref`.
        # Returning it verbatim left refs deeper inside it unresolved, and `jsonschema` then
        # tried to resolve them against the fragment it had been handed:
        # `PointerToNowhere: '/components/schemas/GeoRadius' does not exist within {...}`.
        # A filter nests Filter -> must -> Condition -> operation -> oneOf -> GeoRadius, which
        # is past the cap. "Anything" is the honest answer when the validator cannot see the
        # whole schema; a dangling ref is not.
        return {}
    if isinstance(node, list):
        return [_resolve(n, depth + 1) for n in node]
    if "$ref" in node:
        name = node["$ref"].rsplit("/", 1)[-1]
        target = _spec.get("components", {}).get("schemas", {}).get(name)
        return _resolve(target, depth + 1) if target is not None else {}

    # `get`, never `pop`: `_spec` is shared and resolved many times. Popping mutated the
    # document, so the flag was consumed by the first operation to resolve a given schema and
    # every later one saw a non-nullable copy -- which looked exactly like a real mismatch.
    nullable = node.get("nullable", False)
    out = {k: _resolve(v, depth + 1) for k, v in node.items() if k != "nullable"}
    if not nullable:
        return out
    if "type" in out:
        types = out["type"] if isinstance(out["type"], list) else [out["type"]]
        out["type"] = list(dict.fromkeys([*types, "null"]))
        return out
    # `allOf: [{$ref}]` with `nullable`, which is how utoipa spells `Option<Struct>`.
    return {"anyOf": [out, {"type": "null"}]}


def find(method, path):
    """The (template, operation) for a concrete path, or None."""
    if _routes is None:
        return None
    full = path if path.startswith("/api/v1") else "/api/v1" + path
    full = full.split("?", 1)[0]
    for m, template, pattern, operation in _routes:
        if m == method.upper() and pattern.match(full):
            return template, operation
    return None


def check(method, path, body, response, expect_ok=True):
    """Validate one exchange. Raises on a request mismatch; records a response mismatch.

    `expect_ok=False` is the test saying "this request is meant to be refused" -- a negative
    test sending `top_k: -1` or `search_mode: "wat"` on purpose. Those bodies are supposed to
    violate the document; validating them would fail the tests whose subject is the refusal.
    The response is still checked, because how a refusal is *shaped* is exactly what those
    tests are about.
    """
    if _routes is None:
        return
    found = find(method, path)
    if found is None:
        return  # not a documented route; `api_contract_test.rs` is what covers coverage
    template, operation = found
    import jsonschema

    if body is not None and expect_ok:
        schema = (operation.get("requestBody", {}).get("content", {})
                  .get("application/json", {}).get("schema"))
        if schema:
            try:
                jsonschema.validate(body, _resolve(schema))
            except jsonschema.ValidationError as e:
                raise AssertionError(
                    f"{method} {template}: the request body does not match the OpenAPI "
                    f"document.\n  at {list(e.absolute_path) or '<root>'}: {e.message}\n"
                    f"  Either the document is wrong or this test is; both are worth "
                    f"stopping for. DXMT_OPENAPI_VALIDATE=0 skips this."
                ) from None

    responses = operation.get("responses", {})
    spec_for_status = responses.get(str(response.status_code)) or responses.get("default")
    key = (method.upper(), template, response.status_code)
    if spec_for_status is None:
        message = f"the document lists {sorted(responses)} and the server answered {response.status_code}"
    else:
        schema = spec_for_status.get("content", {}).get("application/json", {}).get("schema")
        if not schema or not response.content:
            return
        try:
            jsonschema.validate(response.json(), _resolve(schema))
            return
        except jsonschema.ValidationError as e:
            message = f"at {list(e.absolute_path) or '<root>'}: {e.message}"
        except ValueError:
            message = "the response is not JSON, and the document says it is"

    if (method.upper(), template) in STRICT:
        raise AssertionError(
            f"{method} {template} -> {response.status_code}: the response does not match the "
            f"OpenAPI document.\n  {message}\n"
            f"  This operation is in helpers/openapi.py's STRICT set, so this is a failure. "
            f"Fix the `#[utoipa::path]` annotation or the handler."
        )
    observed.setdefault(key, message)


def report():
    """One line per operation whose responses do not match, for the end of the run."""
    if not observed:
        return ""
    out = [f"{len(observed)} operations answer something the OpenAPI document does not "
           f"describe. They are outside helpers/openapi.py's STRICT set, so they did not fail:"]
    for (method, template, status), message in sorted(observed.items()):
        out.append(f"  {method:<6} {template} -> {status}: {message[:120]}")
    out.append("  Fix the annotation, then add the operation to STRICT so it stays fixed.")
    return "\n".join(out)
