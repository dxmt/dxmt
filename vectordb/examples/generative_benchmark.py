#!/usr/bin/env python3
"""Measure retrieval on *your own* documents, with a benchmark generated from them.

The published datasets -- SIFT, GIST, GloVe, the rest of `ann-benchmarks` -- come with the
answers, which is what makes a recall number mean anything. Your corpus does not. That leaves
two questions that look alike and are not:

    Is the index faithful?          `search_mode: "exact"` answers this. It scores every live
                                    row and is the ground truth the other modes approximate.
    Is this embedding model right   Nothing in this repository answered this, and it is the
    for my documents?               one that decides whether a RAG system works.

An index can be exact and the retrieval still useless, because the model put the wrong passage
first. Generative benchmarking, which Chroma's `sample_apps/generative_benchmarking` describes
(Apache 2.0 -- the method, not the code), is a way to ask the second question without labelling
anything by hand: for each passage, have an LLM write the query a user would ask that *this*
passage answers. The pair is the label, by construction. Then measure whether retrieval brings
that passage back.

**What this adds to the method.** The original cannot separate the two questions above, because
Chroma has no exact mode: a miss is a miss. Here every query runs twice, once through the graph
and once through `search_mode: "exact"`, and each miss is attributed:

    the model's        the exact scan did not rank the source passage first either -- the
                       embedding does not put this query near the passage it came from
    the index's        the exact scan found it and the graph did not

Those are different bugs with different fixes, and a single recall number hides which you have.

The generated queries are cached in `--cache` so a rerun costs nothing and so you can read
them: a generated benchmark is only as good as its queries, and the first thing to do with one
is look at a dozen. An LLM writing a query from a passage will sometimes quote it, which makes
retrieval trivially easy and the score meaningless -- `--show` prints query and passage side by
side so that is visible rather than assumed.

Embedding is the server's own (`embedding` on the table, feature `server-embedding`), so this
measures the path a real caller uses: insert `text`, search with `text`.

    export OPENAI_API_KEY=...
    cd vectordb && cargo run --release -- serve &
    python3 examples/generative_benchmark.py                      # this repo's docs
    python3 examples/generative_benchmark.py --docs ~/my-notes    # yours
    python3 examples/generative_benchmark.py --show 5             # look at the queries

`DXMT_URL` points it at another server. The key is read from the environment, is passed to the
server by name (`api_key_env`) rather than by value, and is never printed.
"""

import argparse
import json
import math
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

BASE = os.environ.get("DXMT_URL", "http://localhost:9999").rstrip("/") + "/api/v1"
REPO = Path(__file__).resolve().parent.parent
TABLE = "generative_benchmark"
#: The model the server embeds with, and the one the queries are generated by. Different
#: models on purpose: generating and retrieving with the same family would flatter the result.
EMBED_MODEL = "text-embedding-3-small"
WRITE_MODEL = "gpt-4o-mini"
SOURCES = ["README.md", "CONTRIBUTING.md", "tests/README.md", "examples/README.md",
           "docs/operations/backup-restore.md", "docs/SUPPORT_MATRIX.md",
           "docs/architecture/disk-index.md"]
KS = (1, 3, 5, 10)


def req(method, path, body=None, timeout=300):
    request = urllib.request.Request(
        BASE + path,
        data=None if body is None else json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
        method=method,
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as r:
            return r.status, json.load(r)
    except urllib.error.HTTPError as e:
        raw = e.read()
        return e.code, (json.loads(raw) if raw else {})
    except urllib.error.URLError as e:
        print(f"no server at {BASE}: {e}\n\n    cd vectordb && cargo run --release -- serve\n",
              file=sys.stderr)
        sys.exit(1)


def chunks_of(path: Path, source: str):
    """Split on blank lines, then glue small pieces together.

    The same splitter as `rag_eval.py`, for the same reason: a table row or a one-line heading
    carries no context of its own, so chunks are grown to at least `MIN` characters and each
    one can stand alone. A passage too small to stand alone cannot have a fair query written
    from it either.
    """
    MIN, MAX = 320, 1100
    text = path.read_text(encoding="utf8", errors="replace")
    out, buf = [], ""
    for para in re.split(r"\n\s*\n", text):
        para = para.strip()
        if not para:
            continue
        buf = f"{buf}\n\n{para}" if buf else para
        if len(buf) >= MIN:
            out.append(buf[:MAX])
            buf = ""
    if len(buf) >= 120:
        out.append(buf)
    return [(f"{source}#{i}", c) for i, c in enumerate(out)]


def corpus(docs_dir):
    if docs_dir:
        root = Path(docs_dir).expanduser()
        files = sorted(p for p in root.rglob("*") if p.suffix in (".md", ".txt", ".rst"))
        if not files:
            sys.exit(f"no .md, .txt or .rst under {root}")
        return [c for p in files for c in chunks_of(p, str(p.relative_to(root)))]
    return [c for s in SOURCES if (REPO / s).exists() for c in chunks_of(REPO / s, s)]


SYSTEM = "You write the question a reader would type into a search box. Output the question " \
         "and nothing else."

PROMPT = """Here is a passage from the documentation of a vector database.

<passage>
{passage}
</passage>

Write one question that a reader would plausibly type into a search box, and that this passage
answers. Constraints, and they matter more than fluency:

* Do not quote the passage. A question sharing a rare phrase with its passage is found by
  string matching and measures nothing.
* Ask about the substance, not about the document. "Where is this documented" is not a query.
* Keep it to one line, the way people actually type: no preamble, often no question mark.

Output the question alone."""


def generate(passages, cache_path, limit):
    """One query per passage, from an LLM, cached on disk."""
    cache = {}
    if cache_path.exists():
        cache = json.loads(cache_path.read_text())

    todo = [(i, t) for i, t in passages[:limit] if i not in cache]
    if todo:
        key = os.environ.get("OPENAI_API_KEY")
        if not key:
            sys.exit("OPENAI_API_KEY is not set, and "
                     f"{len(todo)} passages have no cached query yet")
        try:
            from openai import OpenAI
        except ImportError:
            sys.exit("this needs the OpenAI client: pip install openai")
        client = OpenAI(api_key=key)
        for n, (pid, text) in enumerate(todo, 1):
            r = client.chat.completions.create(
                model=WRITE_MODEL,
                messages=[{"role": "system", "content": SYSTEM},
                          {"role": "user", "content": PROMPT.format(passage=text)}],
            )
            cache[pid] = r.choices[0].message.content.strip()
            if n % 10 == 0 or n == len(todo):
                print(f"  wrote {n}/{len(todo)} queries", flush=True)
        cache_path.write_text(json.dumps(cache, indent=1, ensure_ascii=False))
    return cache


def load(passages):
    req("DELETE", f"/tables/{urllib.parse.quote(TABLE, safe='')}")
    status, body = req("POST", "/tables", {
        "name": TABLE,
        # `dimension` is *omitted*, not zero: the server probes the model once and takes the
        # width. Sending 0 explicitly is a 400 ("Dimension must be between 1 and 4096") --
        # the API layer supplies the sentinel for an absent field, and validation runs on
        # what the caller sent. This is the only example that exercises that path.
        "distance_metric": "cosine",
        "embedding": {"model": EMBED_MODEL, "api_key_env": "OPENAI_API_KEY"},
    })
    if status != 200:
        sys.exit(f"could not create the table: {status} {body}\n"
                 "a table that names a model needs the server built with `server-embedding` "
                 "(it is a default feature) and OPENAI_API_KEY set *in the server's* "
                 "environment -- the key is read there, not here.")
    for s in range(0, len(passages), 32):
        part = passages[s : s + 32]
        status, body = req("POST", f"/tables/{TABLE}/records", {
            "records": [{"id": pid, "text": text, "payload": {"source": pid.split("#")[0]}}
                        for pid, text in part]})
        if status != 200:
            sys.exit(f"insert failed: {status} {body}")
        print(f"  embedded and stored {min(s + 32, len(passages))}/{len(passages)}", flush=True)


def rank_of(pid, hits):
    """1-based rank of `pid` among `hits`, or None."""
    for n, h in enumerate(hits, 1):
        if h["id"] == pid:
            return n
    return None


def measure(queries, mode, k):
    ranks = {}
    for pid, q in queries.items():
        body = {"text": q, "top_k": k}
        if mode:
            body["search_mode"] = mode
        status, resp = req("POST", f"/tables/{TABLE}/search", body)
        if status != 200:
            sys.exit(f"search failed: {status} {resp}")
        ranks[pid] = rank_of(pid, resp["data"]["hits"])
    return ranks


def report(name, ranks):
    n = len(ranks)
    row = [f"{name:<10}"]
    for k in KS:
        row.append(f"{sum(1 for r in ranks.values() if r and r <= k) / n:>8.4f}")
    mrr = sum(1 / r for r in ranks.values() if r) / n
    ndcg = sum(1 / math.log2(r + 1) for r in ranks.values() if r and r <= 10) / n
    row.append(f"{mrr:>7.4f}")
    row.append(f"{ndcg:>8.4f}")
    print("  ".join(row))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--docs", default=None, help="a directory of .md/.txt/.rst; default: this repo")
    ap.add_argument("--limit", type=int, default=60, help="passages to benchmark")
    ap.add_argument("--cache", default=None, help="where the generated queries live")
    ap.add_argument("--show", type=int, default=0, help="print this many query/passage pairs")
    ap.add_argument("--regenerate", action="store_true", help="discard the cached queries")
    args = ap.parse_args()

    passages = corpus(args.docs)
    if len(passages) < 10:
        sys.exit(f"only {len(passages)} passages; too few to say anything")
    cache_path = Path(args.cache or (REPO / "examples" / ".generative_benchmark.json"))
    if args.regenerate and cache_path.exists():
        cache_path.unlink()

    print(f"{len(passages)} passages, benchmarking {min(args.limit, len(passages))}")
    print(f"queries by {WRITE_MODEL}, embeddings by {EMBED_MODEL} (server-side)\n")

    print("1. writing a query for each passage")
    queries = generate(passages, cache_path, args.limit)
    by_id = dict(passages)
    queries = {i: q for i, q in queries.items() if i in by_id}

    if args.show:
        print(f"\n  the first {args.show}, to check the questions are not quoting the text:")
        for pid in list(queries)[: args.show]:
            print(f"\n  [{pid}]\n  Q: {queries[pid]}\n  A: {by_id[pid][:180]}...")
        print()

    print("\n2. loading the corpus, the server doing the embedding")
    load(passages[: args.limit])

    print("\n3. retrieving\n")
    print(f"{'mode':<10}  " + "  ".join(f"recall@{k:<2}" for k in KS) + "      MRR     NDCG@10")
    ranks = {}
    for mode in ("fast", "normal", "accurate", "exact"):
        ranks[mode] = measure(queries, mode, max(KS))
        report(mode, ranks[mode])

    # The attribution this port exists for.
    exact, graph = ranks["exact"], ranks["accurate"]
    model_misses = [p for p, r in exact.items() if r is None or r > 1]
    index_misses = [p for p in exact if exact[p] == 1 and graph[p] != 1]
    print(f"\n  of {len(exact)} queries, the source passage was not first for "
          f"{len(model_misses)}:")
    print(f"    {len(model_misses) - len(index_misses):>3} the exact scan did not rank it "
          f"first either -- the embedding, not the index")
    print(f"    {len(index_misses):>3} the exact scan had it first and the graph did not "
          f"-- the index")
    if index_misses:
        print(f"        {', '.join(index_misses[:5])}")

    worst = sorted((r or 10**6, p) for p, r in exact.items())[-3:]
    print("\n  the three the embedding placed furthest from their own passage:")
    for r, p in reversed(worst):
        where = "not in the top 10" if r > 10 else f"rank {r}"
        print(f"    {where:<18} {p}")
        print(f"      Q: {queries[p]}")

    print(f"\n  queries cached in {cache_path}; read them before trusting any of the above.")
    req("DELETE", f"/tables/{urllib.parse.quote(TABLE, safe='')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
